"""
闭包介绍
    解释：
        闭包是指在函数内部定义的函数，该函数可以访问外部函数的变量。
    格式：
        def 外部函数名(形参):
            外部函数的(局部)变量

            def 内部函数名(形参):
                使用外部函数的变量

            return 内部函数名

细节：
    函数名 和 函数名() 是不同的东西, 函数名是函数对象 函数名() 是函数的调用表达式。
    前提条件：
        有嵌套
        有引用
        有返回值
"""

def outer(num1):
    def inner(num2):
        sum = num1 + num2
        print(f'和是{sum}')
    return inner


outer(50)(20)


